test('exact old source lookup, scoped date/text search and reference context validate membership, pairs and whole source ranges', async t => {
  const c = await testApp(); t.after(() => c.close());
  const alice = await phoneSignIn(c.app, '+15551112001', 'ref_alice');
  const bob = await phoneSignIn(c.app, '+15551112002', 'ref_bob');
  const carol = await phoneSignIn(c.app, '+15551112003', 'ref_carol');
  const service = new MessagingService(c.db);
  const chat = await service.createDirectChat(alice.user.id, bob.user.id);
  const other = await service.createDirectChat(alice.user.id, carol.user.id);
  const source = await service.send(bob.user.id, chat.id, { kind: 'text', text: 'A year ago 👩‍💻 we booked 100% of the room.' }, randomUUID());
  await c.db.query("UPDATE messages SET created_at='2025-10-12T12:00:00Z' WHERE id=$1", [source.id]);
  for (let i = 0; i < 31; i++) await service.send(alice.user.id, chat.id, { kind: 'text', text: `Recent ${i}` }, randomUUID());
  assert.equal((await service.messages(alice.user.id, chat.id)).some(m => m.id === source.id), false);
  const headers = { authorization: `Bearer ${alice.token}` };
  const get = await c.app.inject({ url: `/v1/chats/${chat.id}/messages/${source.id}`, headers });
  assert.equal(get.statusCode, 200); assert.equal(get.json().text, source.text);
  assert.equal((await c.app.inject({ url: `/v1/chats/${other.id}/messages/${source.id}`, headers })).statusCode, 404);
  assert.equal((await c.app.inject({ url: `/v1/chats/${chat.id}/messages/${source.id}`, headers: { authorization: `Bearer ${carol.token}` } })).statusCode, 404);
  const search = await service.searchMessages(alice.user.id, chat.id, { query: '100%', afterDate: '2025-10-01T00:00:00Z', beforeDate: '2025-11-01T00:00:00Z', limit: 1 });
  assert.deepEqual(search.messages.map(m => m.id), [source.id]);
  await assert.rejects(service.searchMessages(carol.user.id, chat.id, {}), { status: 404 });
  await assert.rejects(service.searchMessages(alice.user.id, other.id, { before: source.id }), { status: 404 });
  const context = { route: `/chat/${chat.id}`, revision: 1, reference: { chatId: chat.id, messageId: source.id, revision: 10, focus: { start: 0, end: 10 } } };
  await assertContextAccess(c.db, alice.user.id, context);
  await assert.rejects(assertContextAccess(c.db, alice.user.id, { ...context, reference: { ...context.reference, focus: { start: 12, end: 13 } } }), { code: 'INVALID_FOCUS' });
  assert.equal(sameContext(context, { ...context, reference: { ...context.reference, revision: 11 } }), false);
  const state = new AssistantState(c.db), session = await state.session(alice.user.id), clientId = randomUUID();
  await state.accept(alice.user.id, session.id, clientId, 'Reply to this.', undefined, context);
  await assert.rejects(state.accept(alice.user.id, session.id, clientId, 'Reply to this.', undefined, { ...context, reference: { ...context.reference, revision: 11 } }), { status: 409 });
});

test('show tools use stored source only and await real ACK; narration is owned, one-use and current generation', async t => {
  const c = await testApp(); t.after(() => c.close());
  const owner = await phoneSignIn(c.app, '+15551112101', 'ref_owner');
  const friend = await phoneSignIn(c.app, '+15551112102', 'ref_friend');
  const service = new MessagingService(c.db), state = new AssistantState(c.db);
  const chat = await service.createDirectChat(owner.user.id, friend.user.id);
  const source = await service.send(friend.user.id, chat.id, { kind: 'text', text: 'Original source, not assistant narration.' }, randomUUID());
  const session = await state.session(owner.user.id);
  await state.accept(owner.user.id, session.id, randomUUID(), 'What did she mean?', undefined, { route: '/mia', revision: 0 });
  const turn = await state.claim(randomUUID()); assert.ok(turn);
  const tools = toolsFor('mia', { db: c.db, state, turn, signal: new AbortController().signal, delegate: async () => '' });
  await assert.rejects(tools.get('show_message')!.execute({ chatId: chat.id, messageId: source.id, focus: null, narration: null, text: 'Fabrication' }));
  let finished = false;
  const delivery = { tone: 'gentle', pace: 'steady', warmth: 'reserved' } as const;
  const work = tools.get('show_message')!.execute({ chatId: chat.id, messageId: source.id, focus: null, narration: 'She is referring to your earlier plan.', delivery }).then(result => { finished = true; return result; });
  let action: { id: string; payload: { narration: string } } | undefined;
  for (let attempt = 0; !action && attempt < 100; attempt++) { [action] = await c.db.query('SELECT id,payload FROM device_actions WHERE turn_id=$1', [turn.id]); if (!action) await delay(10); }
  assert.ok(action); assert.equal(finished, false);
  await assert.rejects(state.actionSpeech(friend.user.id, session.id, turn.id, action.id), { status: 404 });
  await tools.get('set_speech_delivery')!.execute({ tone: 'light', pace: 'steady', warmth: 'friendly' });
  const spoken = await state.actionSpeech(owner.user.id, session.id, turn.id, action.id);
  assert.equal(spoken.text, action.payload.narration);
  assert.deepEqual(spoken.delivery, delivery, 'a later final-reply style cannot change a source narration snapshot');
  await assert.rejects(state.actionSpeech(owner.user.id, session.id, turn.id, action.id), { code: 'STALE_SPEECH' });
  await assert.rejects(state.acknowledgeAction(owner.user.id, action.id, true, { context: { route: '/mia', revision: 0 } }), { status: 409 });
  const reference = { chatId: chat.id, messageId: source.id, revision: 1 };
  await state.acknowledgeAction(owner.user.id, action.id, true, { reference, context: { route: `/chat/${chat.id}`, revision: 1, reference } });
  assert.equal((await work as { state: string }).state, 'completed');
  const second = await state.action(turn, new AbortController().signal, 'show_message', { chatId: chat.id, messageId: source.id, narration: 'A later explanation.' });
  await state.interrupt(owner.user.id, session.id);
  await assert.rejects(state.actionSpeech(owner.user.id, session.id, turn.id, second.id), { code: 'STALE_SPEECH' });
  assert.equal(toolsFor('messaging', { db: c.db, state, turn, signal: new AbortController().signal, delegate: async () => '' }).has('get_message'), true);
});
